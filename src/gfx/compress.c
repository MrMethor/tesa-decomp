/* ---- LZSS (1000:7608) ------------------------------------------------- */

#define LZSS_N 4096
#define LZSS_F 18

size_t lzss_decode(const uint8_t *in, size_t in_len, uint8_t *out, size_t out_cap)
{
	uint8_t  ring[LZSS_N];
	size_t   ip = 0, op = 0;
	unsigned r = LZSS_N - LZSS_F;   /* 0xFEE */
	unsigned flags = 0;

	memset(ring, ' ', LZSS_N - LZSS_F);
	memset(ring + LZSS_N - LZSS_F, 0, LZSS_F);   /* the original leaves these unset */

	for (;;) {
		flags >>= 1;
		if (!(flags & 0x100)) {
			if (ip >= in_len)
				break;
			flags = in[ip++] | 0xFF00;
		}
		if (flags & 1) {
			uint8_t c;
			if (ip >= in_len)
				break;
			c = in[ip++];
			if (op < out_cap)
				out[op] = c;
			op++;
			ring[r] = c;
			r = (r + 1) & (LZSS_N - 1);
		} else {
			unsigned pos, len, k;
			if (ip + 1 >= in_len)
				break;   /* the original also stops when a pair is cut short */
			pos = in[ip] | ((in[ip + 1] & 0xF0u) << 4);
			len = (in[ip + 1] & 0x0Fu) + 2;
			ip += 2;
			for (k = 0; k <= len; k++) {
				uint8_t c = ring[(pos + k) & (LZSS_N - 1)];
				if (op < out_cap)
					out[op] = c;
				op++;
				ring[r] = c;
				r = (r + 1) & (LZSS_N - 1);
			}
		}
	}
	return op < out_cap ? op : out_cap;
}

