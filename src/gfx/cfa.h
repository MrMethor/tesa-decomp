/* .CFA animations (creatures, first-person weapons, body parts, spells).
 *
 * Header (field use from the 3D sprite path 1000:c62c-c6f6 and the
 * loaders 1000:1a5c / 39cf:08da):
 *   0x00 uint16 width          pixels
 *   0x02 uint16 height
 *   0x04 uint16 row_bytes      bytes per packed row = (bpp * width + 7) / 8
 *   0x06 uint16 unknown1       (not used by the decode path)
 *   0x08 uint16 unknown2       (not used by the decode path)
 *   0x0A uint8  bpp            bits per pixel (1-8; 8 = no colour table)
 *   0x0B uint8  frames
 *   0x0C uint16 offset[frames] file offset of each frame's data
 *   0x4A uint16 size           file size (the loader overwrites it with the real size)
 *   0x4C uint8  colours[]      colour table, up to the first frame's offset
 *                              (empty for 8-bit sprites: pixels are palette indices)
 * Frame data: RLE as image flag 0x0001 (1000:5b65) giving row_bytes*height
 * bytes of packed pixels. Pixels are packed MSB first: pixel x is
 * ((b[n] << 8 | b[n+1]) >> (16 - bpp - (x*bpp & 7))) & ((1 << bpp) - 1)
 * with n = x*bpp / 8 (unpack code generated by 1000:7a2b). The index goes
 * through colours[] (and the shading table, when drawing). Index 0 is not
 * drawn when the sprite is drawn transparently.
 */
#ifndef ARENA_CFA_H
#define ARENA_CFA_H

#include <stdint.h>

#define CFA_TABLE_OFFSET 0x4C

typedef struct arena_cfa {
	uint16_t       width, height, row_bytes;
	uint16_t       unknown1, unknown2;
	uint8_t        bpp, frames;
	const uint8_t *colours;     /* points into data */
	int            ncolours;
	uint8_t       *data;        /* whole file, owned */
	uint32_t       size;
} arena_cfa;

int  cfa_load(const char *name, arena_cfa *out);
int  cfa_from_bytes(uint8_t *buf, uint32_t size, arena_cfa *out);   /* takes ownership */
void cfa_free(arena_cfa *cfa);

/* Decode frame `index` to width*height palette indices (colour table
 * applied; transparent pixels come out as colours[0]). If raw_index is not
 * NULL it also receives the untranslated indices. 0 on success, -1 on error.
 * *consumed (optional) gets the number of RLE input bytes used. */
int  cfa_frame(const arena_cfa *cfa, unsigned index, uint8_t *out, uint8_t *raw_index,
               uint32_t *consumed);

#endif
